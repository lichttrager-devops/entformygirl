// Функция для перемешивания массива (Алгоритм Фишера-Йетса)
function shuffleArray(array) {
    for (let i = array.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [array[i], array[j]] = [array[j], array[i]];
    }
}

// Функция для выбора случайных 40 вопросов из большой базы
function selectRandomQuestions(allQuestions) {
    const totalQuestionsRequired = 40;
    
    // 1. Создаем копию массива и перемешиваем его
    const shuffledQuestions = [...allQuestions];
    shuffleArray(shuffledQuestions);
    
    // 2. Выбираем первые 40
    return shuffledQuestions.slice(0, totalQuestionsRequired);
}


document.addEventListener('DOMContentLoaded', () => {

    // =================================================================
    // 4. АВТОМАТИЧЕСКИЙ ВЫБОР ПРЕДМЕТА (ИСПРАВЛЕНО)
    // =================================================================
    
    let questionsToUse;
    
    // Проверяем заголовок HTML-страницы, чтобы понять, какой тест загружать
    if (document.title.includes("Основы права")) {
        questionsToUse = allQuizQuestions;
        console.log("Загружен тест по Основам права.");
    } else if (document.title.includes("Всемирная история")) {
        questionsToUse = allWorldHistoryQuestions;
        console.log("Загружен тест по Всемирной истории.");
    } else {
        // Резервный вариант, если заголовок не распознан (например, на index.html)
        // На главной странице это не вызовет ошибки, так как там нет quiz-container
        console.log("Главная страница или неизвестный тест.");
        questionsToUse = []; // Пустой массив, чтобы ничего не делать
    }
    
    // =================================================================
    
    // Находим элементы только если мы на странице теста
    const quizContainer = document.querySelector('.quiz-container');
    if (!quizContainer) {
        // Если мы не на странице теста (например, на index.html), прекращаем выполнение скрипта
        return;
    }

    // !!! Выбираем 40 случайных вопросов из ВЫБРАННОЙ БАЗЫ !!!
    const quizQuestions = selectRandomQuestions(questionsToUse);
    const totalQuestions = 40; // Фиксированный размер ЕНТ

    const questionText = document.getElementById('question-text');
    const optionsContainer = document.getElementById('options-container');
    const checkBtn = document.getElementById('check-btn');
    const nextBtn = document.getElementById('next-btn');
    const feedbackArea = document.getElementById('feedback');
    const progressIndicator = document.getElementById('progress-indicator');
    const currentQSpan = document.getElementById('current-q');
    const resultsScreen = document.getElementById('results-screen');
    const finalScoreSpan = document.getElementById('final-score');

    let currentQuestionIndex = 0;
    let score = 0;
    let selectedOptionIndex = null;


    // Функция для обновления индикатора прогресса
    function updateProgress() {
        // Условие для корректного отображения прогресса на последнем вопросе
        const progressValue = currentQuestionIndex;
        const percentage = (progressValue / totalQuestions) * 100;
        progressIndicator.style.width = `${percentage}%`;
        
        // Отображение "X из 40"
        if (progressValue >= totalQuestions) {
             currentQSpan.textContent = totalQuestions;
        } else {
             currentQSpan.textContent = progressValue + 1;
        }
    }
    
    // Функция для загрузки вопроса
    function loadQuestion() {
        if (currentQuestionIndex >= totalQuestions) {
            showResults();
            return;
        }

        // Проверяем, есть ли вопросы
        if (!quizQuestions || quizQuestions.length === 0) {
            questionText.textContent = "Ошибка: Вопросы для этого предмета не найдены.";
            optionsContainer.innerHTML = '';
            checkBtn.style.display = 'none';
            return;
        }

        const q = quizQuestions[currentQuestionIndex];
        
        // Перемешиваем варианты ответа, чтобы не заучивать последовательность
        let shuffledOptions = q.options.map((text, index) => ({ text, originalIndex: index }));
        shuffleArray(shuffledOptions);
        
        // Находим новый индекс правильного ответа
        const newAnswerIndex = shuffledOptions.findIndex(opt => opt.originalIndex === q.answerIndex);

        // Обновляем текущий объект вопроса для корректной проверки
        const currentQ = {
            question: q.question,
            options: shuffledOptions.map(opt => opt.text),
            answerIndex: newAnswerIndex,
            explanation: q.explanation
        };
        
        questionText.textContent = `${currentQuestionIndex + 1}. ${currentQ.question}`;
        optionsContainer.innerHTML = '';
        feedbackArea.style.display = 'none';
        nextBtn.style.display = 'none';
        checkBtn.style.display = 'block';
        selectedOptionIndex = null;
        
        currentQ.options.forEach((option, index) => {
            const btn = document.createElement('button');
            btn.classList.add('option-btn');
            btn.textContent = option;
            btn.dataset.index = index;
            btn.addEventListener('click', () => selectOption(btn, index));
            optionsContainer.appendChild(btn);
        });

        // Сохраняем правильный индекс для проверки
        optionsContainer.dataset.correctIndex = newAnswerIndex;

        updateProgress();
    }
    
    // Функция выбора варианта
    function selectOption(selectedBtn, index) {
        document.querySelectorAll('.option-btn').forEach(btn => {
            btn.classList.remove('selected');
        });

        selectedBtn.classList.add('selected');
        selectedOptionIndex = index;
    }
    
    // Функция проверки ответа
    checkBtn.addEventListener('click', () => {
        if (selectedOptionIndex === null) {
            alert("Пожалуйста, выберите один из вариантов ответа.");
            return;
        }

        const correctIndex = parseInt(optionsContainer.dataset.correctIndex);
        const q = quizQuestions[currentQuestionIndex]; // Получаем оригинальный вопрос для объяснения
        const isCorrect = selectedOptionIndex === correctIndex;
        
        feedbackArea.style.display = 'block';
        feedbackArea.innerHTML = `<strong>${isCorrect ? 'Верно!' : 'Ошибка!'}</strong> ${q.explanation}`;
        
        // Обновить стили кнопок
        document.querySelectorAll('.option-btn').forEach((btn, index) => {
            btn.disabled = true;
            if (index === correctIndex) {
                btn.classList.add('correct');
            } else if (index === selectedOptionIndex && !isCorrect) {
                btn.classList.add('incorrect');
            }
        });
        
        if (isCorrect) {
            score++;
            feedbackArea.classList.remove('incorrect-feedback');
            feedbackArea.classList.add('correct-feedback');
        } else {
            feedbackArea.classList.remove('correct-feedback');
            feedbackArea.classList.add('incorrect-feedback');
        }

        checkBtn.style.display = 'none';
        nextBtn.style.display = 'block';
    });
    
    // Функция перехода к следующему вопросу
    nextBtn.addEventListener('click', () => {
        currentQuestionIndex++;
        loadQuestion();
    });
    
    // Функция отображения результатов (С ФОКУСОМ НА ИСПРАВЛЕНИЕ)
    function showResults() {
        quizContainer.style.display = 'none';
        resultsScreen.style.display = 'block';
        
        // Обновляем итоговый счет
        finalScoreSpan.textContent = score;
        
        // Находим элементы для правильных/неправильных ответов
        const correctEl = document.getElementById('correct-count');
        const incorrectEl = document.getElementById('incorrect-count');
        
        const incorrect = Math.max(0, totalQuestions - score);
        
        // Обновляем текст (с проверкой, что элементы существуют)
        if (correctEl) {
            correctEl.textContent = score;
        }
        if (incorrectEl) {
            incorrectEl.textContent = incorrect;
        }
        
        updateProgress(); // Обновляем прогресс до 100%
    }

    // Запуск теста
    loadQuestion();
});
